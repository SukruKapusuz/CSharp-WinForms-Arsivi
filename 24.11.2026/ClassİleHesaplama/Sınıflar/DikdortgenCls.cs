using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace ClassİleHesaplama.Sınıflar
{
    internal class DikdortgenCls
    {
        private int a, b;

        public DikdortgenCls()
        {
            this.a = a;
            this.b = b;

        }
        public int AlanHesapla(int a, int b)
        {
            return a * b;
        }
        public int CevreHesapla(int a, int b)
        {
            return 2 * (a + b);
        }

    }
}
